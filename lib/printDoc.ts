export function printHeaderHtml(opts: {
  companyName: string;
  companyTag?: string;
  docTitle: string;
  docSubtitle?: string;
  meta: [string, string][];
}): string {
  const metaRows = opts.meta
    .map(([k, v]) => `<tr><td class="k">${escapeHtml(k)}</td><td>: ${escapeHtml(v)}</td></tr>`)
    .join("");
  return `
  <table class="doc-hdr">
    <tbody><tr>
      <td class="company">
        <div class="name">${escapeHtml(opts.companyName)}</div>
        <div class="tag">${escapeHtml(opts.companyTag ?? "")}</div>
      </td>
      <td class="title">
        <div class="t">${escapeHtml(opts.docTitle)}</div>
        <div class="s">${escapeHtml(opts.docSubtitle ?? "")}</div>
      </td>
      <td class="meta"><table><tbody>${metaRows}</tbody></table></td>
    </tr></tbody>
  </table>`;
}

export function sectionHtml(letter: string, label: string): string {
  return `<span class="ph">${escapeHtml(letter)} &middot; ${escapeHtml(label)}</span>`;
}

export function signOffHtml(roles: string[]): string {
  const cells = roles
    .map(role => `
      <td>
        <div class="line"></div>
        <div class="role">${escapeHtml(role)}</div>
        <div class="sub">Name / Signature / Date</div>
      </td>`)
    .join("");
  return `<div class="signoff"><table><tbody><tr>${cells}</tr></tbody></table></div>`;
}

export function footerNoteHtml(docLabel: string, companyName: string): string {
  const today = new Date().toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" });
  return `<div class="foot">Generated by AJ Shrink ERP &middot; ${escapeHtml(today)} &middot; ${escapeHtml(companyName)} &middot; This is a system generated ${escapeHtml(docLabel)}</div>`;
}

/**
 * Opens the print popup synchronously — call this FIRST, before any `await`,
 * directly inside the click handler. Browsers treat `window.open` as a blocked
 * pop-up unless it runs synchronously in response to a user gesture, so if the
 * document body needs an async fetch first, open the window immediately and
 * write the content into it once the data arrives (see writeAndPrint).
 */
export function openPrintWindow(): Window | null {
  return window.open("", "_blank", "width=1050,height=820");
}

export function writeAndPrint(win: Window, title: string, bodyHtml: string): void {
  win.document.write(`<!doctype html><html><head><title>${escapeHtml(title)}</title><style>${PRINT_DOC_CSS}</style></head><body>${bodyHtml}</body></html>`);
  win.document.close();
  win.focus();
  setTimeout(() => { win.print(); }, 400);
}
