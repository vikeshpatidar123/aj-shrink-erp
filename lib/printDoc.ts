// Shared "master document" print template — used by Purchase Requisition,
// Purchase Order, Purchase GRN (and any future voucher print) so every
// printed document shares the same professional A4 layout: branded header,
// lettered sections, bordered tables, and a sign-off block. Modeled on the
// Work Order "Job Card" print, which is the visual quality bar for this app.

export const toNum = (v: unknown): number => Number(v ?? 0) || 0;

export const escapeHtml = (v: unknown): string =>
  String(v ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c] as string));

export const fmtMoney = (n: number): string =>
  Number(n || 0).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });

export const fmtQty = (n: number): string =>
  Number(n || 0).toLocaleString("en-IN", { maximumFractionDigits: 3 });

